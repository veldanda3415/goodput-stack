"""Push one stage of the T4 notebook to Kaggle, wait for it, download its outputs.

    python -m benchmarks.kaggle.run_kaggle --stage smoke
    python -m benchmarks.kaggle.run_kaggle --stage baseline --args "--vllm-versions 0.31.0,0.30.0"
    python -m benchmarks.kaggle.run_kaggle --stage kvgrid --resume benchmarks/results/t4/<run-id>
    python -m benchmarks.kaggle.run_kaggle --stage sweep --no-wait          # push only
    python -m benchmarks.kaggle.run_kaggle --fetch benchmarks/results/t4/<run-id>   # poll + download a pushed run
    python -m benchmarks.kaggle.run_kaggle --stage nccl --machine-shape NvidiaTeslaT4  # 2 x T4 (see below)

Machine shape: `machine_shape` in kernel-metadata.json. Kaggle documents `NvidiaTeslaT4` as "GPU T4 x2"
(Kaggle/kaggle-api docs/kernels_metadata.md, main @ 6894864f, 2026-10-16), and every run in runs.jsonl pushed
with it recorded 2 GPUs (env.json gpu_count). --machine-shape overrides it; the value is recorded in run.json.

What gets pushed: a new version of one generated Kaggle *script* kernel `<user>/goodput-t4` (all stages) (GPU T4, internet on,
private). The script carries a base64 tarball of benchmarks/harness/, benchmarks/gpu_sampler.py and
benchmarks/kaggle/t4_notebook.py (plus, with --resume, the results of an earlier run of the stage, so the
stage skips work already done), extracts it and runs `python -m benchmarks.kaggle.t4_notebook --stage <stage>`.
Each stage writes /kaggle/working/results/<stage>/ (JSONL + raw logs).

Local layout, one directory per push:
    benchmarks/results/t4/<YYYYmmdd-HHMMSS>_<stage>/
        run.json                 push/poll record: kernel ref, git sha, status, wall time, GPU-hours
        results/<stage>/...      everything the stage wrote (downloaded with `kaggle kernels output`)
        kernel.log               Kaggle's log of the script's stdout/stderr
    benchmarks/results/t4/runs.jsonl   one line per push (ledger, incl. GPU-hours)

Auth: the Kaggle CLI's own config (~/.kaggle). The CLI binary is found next to this Python (the .venv) or on PATH.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RESULTS = REPO / "benchmarks" / "results" / "t4"
PAYLOAD_FILES = ["benchmarks/__init__.py", "benchmarks/harness", "benchmarks/gpu_sampler.py",
                 "benchmarks/kaggle/__init__.py", "benchmarks/kaggle/t4_notebook.py"]
TERMINAL = ("complete", "error", "cancelacknowledged", "cancelrequested")


def kaggle_bin() -> str:
    local = Path(sys.executable).parent / "kaggle"
    return str(local) if local.exists() else (shutil.which("kaggle") or "kaggle")


def kaggle(*args: str, check: bool = True) -> str:
    r = subprocess.run([kaggle_bin(), *args], capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    if check and r.returncode:
        raise SystemExit(f"kaggle {' '.join(args)} failed ({r.returncode}): {out}")
    return out


def kaggle_user() -> str:
    m = re.search(r"username:\s*(\S+)", kaggle("config", "view"))
    if not m:
        raise SystemExit("cannot read the Kaggle username from `kaggle config view`")
    return m.group(1)


def git_sha() -> str:
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=REPO,
                           capture_output=True, text=True).stdout.strip()
    return sha + ("-dirty" if dirty else "")


def payload(stage: str, resume: Path | None) -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in PAYLOAD_FILES:
            p = REPO / rel
            if p.exists():
                tar.add(p, arcname=rel, filter=lambda ti: None if "__pycache__" in ti.name else ti)
        if resume:
            prev = resume / "results" / stage
            if not prev.is_dir():
                raise SystemExit(f"--resume: {prev} does not exist")
            # only the result rows: they are what "skip work already done" reads; raw files stay local
            tar.add(prev / f"{stage}.jsonl", arcname=f"resume/{stage}/{stage}.jsonl")
    return base64.b64encode(buf.getvalue()).decode()


SCRIPT = '''# Generated by benchmarks/kaggle/run_kaggle.py - do not edit; regenerate instead.
# stage={stage} run_id={run_id} git={sha}
import base64, io, os, shutil, subprocess, sys, tarfile, time
T0 = time.time()
SRC = "/tmp/goodput-src"
PAYLOAD = "{payload}"
shutil.rmtree(SRC, ignore_errors=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(SRC)
out = "/kaggle/working/results"
os.makedirs(out, exist_ok=True)
if os.path.isdir(SRC + "/resume/{stage}"):
    shutil.copytree(SRC + "/resume/{stage}", out + "/{stage}", dirs_exist_ok=True)
env = dict(os.environ, PYTHONPATH=SRC, GOODPUT_GIT_SHA="{sha}", GOODPUT_RUN_ID="{run_id}", PYTHONUNBUFFERED="1")
rc = subprocess.run([sys.executable, "-m", "benchmarks.kaggle.t4_notebook", "--stage", "{stage}", *{args!r}],
                    cwd=SRC, env=env).returncode
with open(out + "/kernel_session.txt", "w") as f:
    f.write("stage={stage} rc=%d session_s=%.1f\\n" % (rc, time.time() - T0))
print("stage {stage} exit code", rc, "session %.1f s" % (time.time() - T0))
'''


def push(stage: str, args: list[str], resume: Path | None, slug: str = "goodput-t4",
         machine_shape: str = "NvidiaTeslaT4") -> Path:
    user, sha = kaggle_user(), git_sha()
    run_id = f"{datetime.now():%Y%m%d-%H%M%S}_{stage}"
    run_dir = RESULTS / run_id
    run_dir.mkdir(parents=True)
    build = Path(tempfile.mkdtemp(prefix="kaggle-push-"))
    (build / f"{slug}.py").write_text(SCRIPT.format(stage=stage, run_id=run_id, sha=sha, args=args,
                                                    payload=payload(stage, resume)))
    meta = {"id": f"{user}/{slug}", "title": slug, "code_file": f"{slug}.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False,
            "enable_internet": True, "machine_shape": machine_shape, "keywords": [],
            "dataset_sources": [], "kernel_sources": [], "competition_sources": [], "model_sources": []}
    (build / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    out = kaggle("kernels", "push", "-p", str(build))
    shutil.rmtree(build)
    if "error" in out.lower():   # the CLI exits 0 on e.g. "Maximum batch GPU session count of 2 reached."
        shutil.rmtree(run_dir)
        raise SystemExit(f"push failed: {out}")
    rec = {"run_id": run_id, "stage": stage, "args": args, "kernel": meta["id"], "git_sha": sha,
           "resume_from": str(resume.relative_to(REPO)) if resume else None, "machine_shape": meta["machine_shape"],
           "pushed_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"), "push_output": out}
    (run_dir / "run.json").write_text(json.dumps(rec, indent=2) + "\n")
    print(f"pushed {meta['id']} -> {run_dir.relative_to(REPO)}\n{out}")
    return run_dir


def status(kernel: str) -> str:
    out = kaggle("kernels", "status", kernel, check=False)
    m = re.search(r'status "?(?:KernelWorkerStatus\.)?(\w+)', out, re.I)
    return m.group(1).lower() if m else f"unknown: {out[-200:]}"


def fetch(run_dir: Path, poll_s: int, timeout_min: float) -> dict:
    rec = json.loads((run_dir / "run.json").read_text())
    t0, last = time.time(), None
    while True:
        st = status(rec["kernel"])
        if st != last:
            print(f"  {datetime.now():%H:%M:%S} {rec['kernel']}: {st}", flush=True)
            last = st
        if st in TERMINAL:
            break
        if time.time() - t0 > timeout_min * 60:
            print(f"  gave up waiting after {timeout_min} min (kernel still {st}); re-run with --fetch later")
            rec["status"] = f"timeout-waiting ({st})"
            (run_dir / "run.json").write_text(json.dumps(rec, indent=2) + "\n")
            return rec
        time.sleep(poll_s)
    dl = run_dir / "_download"
    bad: list[Path] = []
    for attempt in range(4):
        # `kaggle kernels output` can save a 502 HTML error page in place of a file (quant rerun, 2026-10-15)
        shutil.rmtree(dl, ignore_errors=True)
        rec["output_cmd_output"] = kaggle("kernels", "output", rec["kernel"], "-p", str(dl), check=False)[-2000:]
        bad = [p for p in dl.rglob("*") if p.is_file() and p.stat().st_size < 4096
               and b"502 Server Error" in p.read_bytes()]
        if not bad:
            break
        print(f"  {len(bad)} file(s) came back as a 502 page ({bad[0].name}); retrying download")
        time.sleep(30)
    else:
        rec["download_warning"] = f"files still 502 pages after 4 tries: {[str(p.relative_to(dl)) for p in bad]}"
    if (dl / "results").is_dir():
        # copy file by file; a 502 page never overwrites anything (a re-fetch must not destroy good data)
        bad_rel = {str(p.relative_to(dl)) for p in bad} if bad else set()
        for src in (dl / "results").rglob("*"):
            rel = src.relative_to(dl)
            if src.is_file() and str(rel) not in bad_rel:
                (run_dir / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, run_dir / rel)
    for log in dl.glob("*.log"):
        shutil.copy(log, run_dir / "kernel.log")
    shutil.rmtree(dl, ignore_errors=True)
    session = run_dir / "results" / "kernel_session.txt"
    m = re.search(r"session_s=([\d.]+)", session.read_text()) if session.exists() else None
    if "finished_at_utc" not in rec:   # a re-fetch (re-download) keeps the first completion time
        rec["finished_at_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    rec["status"] = st
    pushed, done = datetime.fromisoformat(rec["pushed_at_utc"]), datetime.fromisoformat(rec["finished_at_utc"])
    rec["wall_push_to_done_min"] = round((done - pushed).total_seconds() / 60, 1)
    # GPU-hours: the script's own session time (start -> stage exit) on a T4 machine. Kaggle's boot/queue
    # time before the script starts is not in it; wall_push_to_done_min is the upper bound.
    rec["script_session_s"] = float(m.group(1)) if m else None
    rec["gpu_hours_script"] = round(rec["script_session_s"] / 3600, 3) if m else None
    rec["gpu_hours_upper_bound"] = round(rec["wall_push_to_done_min"] / 60, 3)
    (run_dir / "run.json").write_text(json.dumps(rec, indent=2) + "\n")
    ledger = RESULTS / "runs.jsonl"
    rows = [json.loads(l) for l in ledger.read_text().splitlines() if l.strip()] if ledger.exists() else []
    rows = [r for r in rows if r["run_id"] != rec["run_id"]]   # a re-fetch replaces the run's line
    rows.append({k: rec.get(k) for k in ("run_id", "stage", "args", "kernel", "git_sha", "status", "pushed_at_utc",
                                         "finished_at_utc", "wall_push_to_done_min", "script_session_s",
                                         "gpu_hours_script", "gpu_hours_upper_bound")})
    ledger.write_text("".join(json.dumps(r) + "\n" for r in rows))
    print(f"  {st}: session {rec['script_session_s']} s, push->done {rec['wall_push_to_done_min']} min -> {run_dir.relative_to(REPO)}")
    return rec


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", help="t4_notebook stage: smoke, baseline, kvgrid, sweep, quant, nccl")
    ap.add_argument("--args", default="", help="extra args for the stage, one shell-quoted string")
    ap.add_argument("--resume", type=Path, help="earlier run dir of the same stage; its results are re-uploaded and skipped")
    ap.add_argument("--fetch", type=Path, help="poll + download an already pushed run dir")
    ap.add_argument("--no-wait", action="store_true", help="push only")
    ap.add_argument("--kernel", default="goodput-t4",
                    help="kernel slug (default goodput-t4: the one with the HF_TOKEN secret attached; a second slug "
                         "lets an ungated stage run at the same time)")
    ap.add_argument("--machine-shape", default="NvidiaTeslaT4",
                    help="kernel-metadata machine_shape (default NvidiaTeslaT4 = Kaggle's 'GPU T4 x2', see above)")
    ap.add_argument("--poll-s", type=int, default=30)
    ap.add_argument("--timeout-min", type=float, default=240)
    a = ap.parse_args()
    if a.fetch:
        rec = fetch(a.fetch.resolve(), a.poll_s, a.timeout_min)
    else:
        if not a.stage:
            ap.error("--stage or --fetch is required")
        import shlex
        run_dir = push(a.stage, shlex.split(a.args), a.resume.resolve() if a.resume else None, a.kernel,
                       a.machine_shape)
        if a.no_wait:
            return
        rec = fetch(run_dir, a.poll_s, a.timeout_min)
    sys.exit(0 if rec.get("status") == "complete" else 1)


if __name__ == "__main__":
    main()
